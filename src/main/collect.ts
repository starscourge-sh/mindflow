import { BrowserWindow, clipboard, ipcMain, nativeImage, type ClipboardItem, type WebContents } from 'electron'
import { execFile } from 'child_process'
import { createHash } from 'crypto'

/**
 * Collect what you copy (Mote's way): while it is on, everything copied
 * anywhere on the Mac is sent to the note that asked, each copy once.
 *
 * Electron has no word for "the clipboard changed" (macOS's change count is
 * not offered), so the clipboard is looked at twice a second while
 * collecting, and only then: a short summary of what is on it (its kinds and
 * a hash of its words or picture) says whether it is a new copy. Nothing runs
 * when no note is collecting, and one look never starts before the last ends.
 *
 * Password managers mark what they copy as concealed or passing
 * (nspasteboard.org); those copies are never read past that mark.
 */

const LOOK_EVERY_MS = 500

/** The marks a password manager or a one-off copy leaves on the clipboard. */
const SECRET = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType', 'com.agilebits.onepassword']

/** What a copy says about itself: its words, its picture, where it came from. */
export interface Copied {
  text: string
  html: string
  image: { mime: string; bytes: Uint8Array } | null
  app: string | null
  url: string | null
  title: string | null
}

let into: WebContents | null = null
let look: ReturnType<typeof setInterval> | undefined
let last = ''
let busy = false

/** A format of the Mac's own clipboard, by its macOS name, the way Electron asks after one. */
const raw = (format: string): string => `electron application/osclipboard;format="${format}"`

const has = (format: string): Promise<boolean> => clipboard.has(raw(format)).catch(() => false)

/** Whether a password manager or a passing copy put this on the clipboard. */
export const isSecret = async (): Promise<boolean> => (await Promise.all(SECRET.map(has))).some(Boolean)

/** One kind from what is on the clipboard, as words, or '' when it is not there. */
async function words(items: ClipboardItem[], type: string): Promise<string> {
  for (const item of items) {
    if (!item.types.includes(type)) continue
    try {
      return await ((await item.getType(type)) as Blob).text()
    } catch {
      return ''
    }
  }
  return ''
}

/** The picture on the clipboard, as the app stores pictures, or null. */
async function picture(items: ClipboardItem[]): Promise<{ mime: string; bytes: Uint8Array } | null> {
  for (const item of items) {
    const mime = item.types.find((type) => type.startsWith('image/'))
    if (!mime) continue
    const bytes = new Uint8Array(await ((await item.getType(mime)) as Blob).arrayBuffer())
    if (!bytes.length) continue
    if (mime === 'image/png' || mime === 'image/jpeg' || mime === 'image/gif' || mime === 'image/webp') return { mime, bytes }
    const image = nativeImage.createFromBuffer(Buffer.from(bytes))
    if (!image.isEmpty()) return { mime: 'image/png', bytes: new Uint8Array(image.toPNG()) }
  }
  return null
}

/** A short summary of what is on the clipboard: the same copy gives the same one. */
async function summary(items: ClipboardItem[]): Promise<string> {
  const hash = createHash('sha1')
  for (const item of items) {
    hash.update(item.types.join(','))
    for (const type of item.types)
      if (type.startsWith('text/') || type.startsWith('image/')) hash.update(new Uint8Array(await ((await item.getType(type)) as Blob).arrayBuffer()))
  }
  return hash.digest('hex')
}

/** The app in front of everything, by its own name, asked of macOS without needing a permission. */
const frontApp = (): Promise<string | null> =>
  new Promise((done) => {
    if (process.platform !== 'darwin') return done(null)
    execFile('/usr/bin/lsappinfo', ['front'], { timeout: 800 }, (error, front) => {
      const asn = /ASN:[\w-]+:/.exec(front)?.[0]
      if (error || !asn) return done(null)
      execFile('/usr/bin/lsappinfo', ['info', '-only', 'name', asn], { timeout: 800 }, (failed, out) => {
        done(failed ? null : (/"(?:LSDisplayName|name)"="([^"]+)"/i.exec(out)?.[1] ?? null))
      })
    })
  })

/** A browser's page, when the copy says which: Chromium browsers mark the page a copy came from. */
async function page(items: ClipboardItem[], html: string): Promise<{ url: string | null; title: string | null }> {
  let url: string | null = null
  for (const format of ['org.chromium.source-url', 'public.url']) {
    if (!(await has(format))) continue
    const said = (await words(items, raw(format))).replace(/\0/g, '').trim()
    if (/^https?:\/\//i.test(said)) {
      url = said
      break
    }
  }
  const title = (await words(items, raw('public.url-name'))).trim() || /<title>([^<]{1,200})<\/title>/i.exec(html)?.[1]?.trim() || null
  return { url, title }
}

/** Read the copy that just arrived: its words, its picture, where it came from. */
async function read(items: ClipboardItem[]): Promise<Copied | null> {
  const text = await words(items, 'text/plain')
  const html = await words(items, 'text/html')
  const image = await picture(items).catch(() => null)
  if (!text.trim() && !image) return null
  return { text, html, image, ...(await page(items, html)), app: await frontApp() }
}

async function tick(): Promise<void> {
  if (!into || into.isDestroyed()) return stop()
  // One look at a time: a big picture can take longer than the gap between looks.
  if (busy) return
  busy = true
  try {
    // A secret copy is passed over whole, before anything of it is read: not read, not sent, not counted.
    if (await isSecret()) return void (last = 'secret')
    const items = await clipboard.read()
    const now = await summary(items)
    if (now === last) return
    last = now
    // Copied inside Haligtree itself (a line of this very note): not collected again.
    if (BrowserWindow.getFocusedWindow()) return
    const copied = await read(items)
    if (copied && into && !into.isDestroyed()) into.send('collect:item', copied)
  } catch {
    // The clipboard could not be read this time: the next look tries again.
  } finally {
    busy = false
  }
}

function stop(): void {
  clearInterval(look)
  look = undefined
  const was = into
  into = null
  if (was && !was.isDestroyed()) was.send('collect:state', false)
}

export function registerCollect(): void {
  ipcMain.handle('collect:start', async (event) => {
    if (into && into !== event.sender && !into.isDestroyed()) into.send('collect:state', false)
    into = event.sender
    // What is on the clipboard already was copied before: only what comes next is collected.
    last = (await isSecret()) ? 'secret' : await summary(await clipboard.read().catch(() => []))
    clearInterval(look)
    look = setInterval(() => void tick(), LOOK_EVERY_MS)
    event.sender.once('destroyed', () => into === event.sender && stop())
    return true
  })
  ipcMain.handle('collect:stop', (event) => {
    if (into === event.sender) stop()
  })
}
