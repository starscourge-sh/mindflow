/** The public-domain landscapes Haligtree ships with, written to a folder of its own; that folder's path. */
export async function builtInScenery(): Promise<string> {
  const files = await Promise.all(([['wanderer.webp', wandererUrl], ['mont-blanc.webp', montBlancUrl], ['lake-tahoe.webp', tahoeUrl], ['landers-peak.webp', landersUrl], ['bernina.webp', berninaUrl], ['evening-prairie.webp', prairieUrl], ['jungfrau.webp', jungfrauUrl], ['harbor-entrance.webp', harborUrl], ['grand-manan.webp', mananUrl], ['lake-lucerne.webp', lucerneUrl], ['penobscot-bay.webp', penobscotUrl], ['sierra-nevada.webp', sierraUrl], ['the-oxbow.webp', oxbowUrl], ['twilight-wilderness.webp', twilightUrl], ['fighting-temeraire.webp', temeraireUrl], ['pine-forest.webp', pineUrl], ['ninth-wave.webp', waveUrl], ['hay-wain.webp', haywainUrl], ['yellowstone.webp', yellowstoneUrl], ['heart-of-the-andes.webp', andesUrl], ['storm-rocky-mountains.webp', stormRockyMountainsUrl], ['yosemite-valley.webp', yosemiteValleyUrl], ['cotopaxi.webp', cotopaxiUrl], ['the-icebergs.webp', theIcebergsUrl], ['savage-state.webp', savageStateUrl], ['schroon-mountain.webp', schroonMountainUrl], ['green-river-cliffs.webp', greenRiverCliffsUrl], ['moonrise-over-the-sea.webp', moonriseOverTheSeaUrl], ['riesengebirge.webp', riesengebirgeUrl], ['rain-steam-speed.webp', rainSteamSpeedUrl], ['dido-building-carthage.webp', didoBuildingCarthageUrl], ['salisbury-cathedral.webp', salisburyCathedralUrl], ['wivenhoe-park.webp', wivenhoeParkUrl], ['rye.webp', ryeUrl], ['dnieper-moonlight.webp', dnieperMoonlightUrl], ['lake-george.webp', lakeGeorgeUrl], ['approaching-thunder-storm.webp', approachingThunderStormUrl], ['birch-grove.webp', birchGroveUrl]] as const)
    .map(async ([name, url]) => ({ name, bytes: new Uint8Array(await (await fetch(url)).arrayBuffer()) })))
  return call<string>('sandbox:scenery', files)
}
