/** Groups that only exist in the main window: their rows need not say so. */
const MAIN_ONLY = ["This week's tasks", 'Matrix', 'Board', 'Settings']
/** Where a key works, said only when it is limited, in plain words: '' when it works wherever you would press it. */
export function whereSaid(one: Shortcut): string {
  if (one.where === 'Both windows' || one.where === 'Anywhere' || one.where === one.group) return ''
  if (one.where === 'Main window' && MAIN_ONLY.includes(one.group)) return ''
  return ({ 'Main window': 'Main window only', 'Quick capture': 'In quick capture', Lists: 'In lists', Writing: 'While writing', Review: 'In Review', Reading: 'While reading', Tidy: 'While tidying', Deciding: 'While deciding', 'The session bubble': 'In the session bubble' } as Record<string, string>)[one.where] ?? one.where
}

/** The list in its groups, in the order they first appear. */
export function grouped(list: Shortcut[] = SHORTCUTS): [string, Shortcut[]][] {
  const groups = new Map<string, Shortcut[]>()
  for (const one of list) groups.set(one.group, [...(groups.get(one.group) ?? []), one])
  return [...groups]
}

/** The ones that match what was typed, by what they do, the keys (as you press them now: `keysOf`), or where. */
export function findShortcuts(query: string, keysOf = (keys: string): string => keys, list = SHORTCUTS): Shortcut[] {
  const q = query.trim().toLowerCase()
  if (!q) return list
  return list.filter((one) => `${one.does} ${keysOf(one.keys)} ${one.where} ${one.group}`.toLowerCase().includes(q))
}
