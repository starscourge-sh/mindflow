// Drag a task card from today to two days later in the week view, and check it moved.
import { open } from './harness.mjs'
const qa = await open()
const { electron, page } = qa
const errors = []
const today = new Date(); today.setHours(15, 0, 0, 0)
const id = await page.evaluate(() => window.api.haligtree('task:add', 'drag me today 3pm').catch((e) => String(e)))
console.log('added', id)
await page.waitForTimeout(2000)
await electron.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().includes('home')); w?.setBounds({ width: 1300, height: 800 }); w?.show() })
await page.waitForTimeout(600)
const home = electron.windows().find((w) => w.url().includes('home'))
home.on('pageerror', (e) => errors.push(e.message))
await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().includes('home'))?.webContents.send('home:open', 'view', 'week'))
await home.waitForTimeout(1200)
await home.keyboard.press('Escape')
await home.waitForTimeout(400)
const card = home.locator('button', { hasText: 'drag me' }).first()
const from = await card.boundingBox()
const target = await home.locator('[data-day="2"]').boundingBox()
console.log('card', !!from, 'target', !!target)
await home.mouse.move(from.x + 20, from.y + 10)
await home.mouse.down()
await home.mouse.move(from.x + 60, from.y + 30, { steps: 5 })
await home.mouse.move(target.x + target.width / 2, target.y + 400, { steps: 12 })
await home.waitForTimeout(150)
const lit = await home.locator('[data-day="2"]').getAttribute('class')
console.log('target lit', lit.includes('ring-1'))
await home.screenshot({ path: process.env.SHOT + '/week-drag.png' })
await home.mouse.up()
await home.waitForTimeout(800)
const tasks = await page.evaluate(() => window.api.haligtree('tasks'))
const t = tasks.find((one) => one.title === 'drag me')
console.log('due now', t?.dueAt, 'days moved', t && Math.round((new Date(t.dueAt) - new Date(new Date().setHours(15, 0, 0, 0))) / 86400000))
console.log('detail opened?', await home.locator('text=Scheduled').count())
console.log('ERRORS', errors.join(' | '))
process.exit(0)
